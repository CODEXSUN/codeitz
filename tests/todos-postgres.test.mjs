import test from 'node:test';
import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { mkdtemp, mkdir, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { sql } from 'kysely';
import { openDatabase } from '../src/api/database.ts';
import { migrate } from '../scripts/database.ts';
import { seed } from '../src/api/modules/todos/database/seeders/seed.ts';
import { PostgresTodoRepository } from '../src/api/modules/todos/repository.ts';
import { TodoStore } from './legacy-todo-store.ts';
import { sqliteSnapshot, importSqlite } from '../src/api/modules/todos/database/import-sqlite.ts';
import { createHttpServer } from '@workspace/framework';
import { registerTodoRoutes } from '../src/api/modules/todos/routes.ts';
const input = { title: 'Personal task', priority: 'medium', category: '', dueDate: '', status: 'open', projectId: '', visibility: 'private' };

test('PostgreSQL migration, no-data seed, SQLite import, writes, categories, concurrency, scheduler and restart', { skip: process.env.CODEITZ_TEST_POSTGRES !== '1' }, async () => {
  const schema = 'todo_test_' + randomBytes(8).toString('hex');
  const base = openDatabase(); const db = base.withSchema(schema);
  const root = await mkdtemp(path.join(tmpdir(), 'codeitz-pg-test-'));
  let app;
  try {
    await base.schema.createSchema(schema).execute();
    await migrate(db, schema); await migrate(db, schema);
    await Promise.all([seed(db), seed(db)]);
    assert.equal(Number((await db.selectFrom('todos').select(sql`count(*)`.as('count')).executeTakeFirst()).count), 0);
    const legacy = new TodoStore(path.join(root, 'todos.sqlite'));
    let old = legacy.create(0, { ...input, category: 'Work', dueDate: '2026-12-05', scheduledAt: '2026-12-05T10:30:00.000Z' });
    const legacyId = old.todos[0].id;
    old = legacy.create(old.revision, { ...input, title: 'Deleted task' });
    old = legacy.remove(old.revision, old.todos[0].id);
    const source = sqliteSnapshot(path.join(root, 'todos.sqlite'));
    const imported = await importSqlite(db, source);
    assert.equal(imported.rows, 2);
    assert.equal((await importSqlite(db, source)).alreadyImported, true);
    const repo = new PostgresTodoRepository(db);
    assert.deepEqual(await repo.read(), legacy.read());
    await seed(db); assert.deepEqual(await repo.read(), legacy.read());
    await assert.rejects(importSqlite(db, { ...source, revision: 999 }), /changed after/);
    let snapshot = await repo.read();
    const existingPublicId = (await db.selectFrom('todos').select('public_id').limit(1).executeTakeFirstOrThrow()).public_id;
    let attempts = 0;
    const { publicId } = await import('../src/api/modules/todos/repository.ts');
    const collisionRepo = new PostgresTodoRepository(db, () => ++attempts === 1 ? existingPublicId : publicId());
    const created = await collisionRepo.create(snapshot.revision, { ...input, title: 'New PostgreSQL todo', category: 'work' });
    assert.equal(attempts, 2);
    const exhausted = new PostgresTodoRepository(db, () => existingPublicId);
    await assert.rejects(exhausted.create(created.revision, { ...input }), /allocate a todo/);
    assert.equal((await repo.read()).revision, created.revision);
    const id = created.todos[0].id; assert.match(id, /^[a-z0-9]{8}$/);
    const concurrent = await Promise.allSettled([repo.update(created.revision, id, { title: 'Winner one' }), repo.update(created.revision, id, { title: 'Winner two' })]);
    assert.equal(concurrent.filter(item => item.status === 'fulfilled').length, 1);
    assert.equal(concurrent.filter(item => item.status === 'rejected').length, 1);
    snapshot = await repo.read();
    snapshot = await repo.reorder(snapshot.revision, [legacyId, id]);
    assert.deepEqual(snapshot.todos.map(item => item.id), [legacyId, id]);
    await assert.rejects(repo.reorder(snapshot.revision, [id]), /every current/);
    snapshot = await repo.changeCategory(snapshot.revision, 'Work', 'Office');
    assert.ok(snapshot.todos.every(item => item.category === 'Office'));
    snapshot = await repo.createCategory(snapshot.revision, 'Personal');
    await assert.rejects(repo.changeCategory(snapshot.revision, 'Office', 'personal'), /already exists/);
    snapshot = await repo.changeCategory(snapshot.revision, 'Office');
    assert.ok(snapshot.todos.every(item => item.category === ''));
    assert.deepEqual(snapshot.categories, ['Personal']);
    const past = new Date(Date.now() - 60000).toISOString();
    snapshot = await repo.update(snapshot.revision, id, { scheduledAt: past });
    assert.equal(await repo.deliverDue(), 1); assert.equal(await repo.deliverDue(), 0);
    snapshot = await repo.read(); assert.ok(snapshot.todos.find(item => item.id === id).remindedAt);
    const restartedConnection = openDatabase().withSchema(schema);
    try { assert.deepEqual(await new PostgresTodoRepository(restartedConnection).read(), snapshot); } finally { await restartedConnection.destroy(); }
    snapshot = await repo.update(snapshot.revision, id, { scheduledAt: '' });
    assert.equal(snapshot.todos.find(item => item.id === id).remindedAt, '');
    await mkdir(path.join(root, 'apps/crm'), { recursive: true }); await mkdir(path.join(root, 'devkit/codeitz'), { recursive: true });
    app = createHttpServer({ name: 'postgres-todos-test', logLevel: 'silent' });
    // Keep fixture database ownership outside the HTTP adapter.
    const adapter = { read:()=>repo.read(), createCategory:(...args)=>repo.createCategory(...args), changeCategory:(...args)=>repo.changeCategory(...args), create:(...args)=>repo.create(...args), update:(...args)=>repo.update(...args), remove:(...args)=>repo.remove(...args), reorder:(...args)=>repo.reorder(...args), deliverDue:(...args)=>repo.deliverDue(...args) };
    registerTodoRoutes(app, root, root, adapter);
    const response = await app.inject({ method: 'PATCH', url: `/api/v1/todos/${id}`, payload: { revision: snapshot.revision, changes: { priority: 'urgent' } } });
    assert.equal(response.statusCode, 200); snapshot = response.json();
    assert.equal((await app.inject({ method: 'PATCH', url: `/api/v1/todos/${legacyId}`, payload: { revision: snapshot.revision, changes: { title: 'Legacy still editable' } } })).statusCode, 200);
    assert.equal((await app.inject({ method: 'POST', url: '/api/v1/todos/categories', headers: { origin: 'https://other.invalid' }, payload: { revision: snapshot.revision, name: 'remote' } })).statusCode, 403);
    const constraints = await sql`SELECT column_name FROM information_schema.columns WHERE table_schema=${schema} AND table_name='todos'`.execute(db);
    assert.ok(constraints.rows.some(row => row.column_name === 'created_by'));
    const foreignKeys = await sql`SELECT referenced.relnamespace::regnamespace::text AS target_schema FROM pg_constraint fk JOIN pg_class owned ON owned.oid=fk.conrelid JOIN pg_class referenced ON referenced.oid=fk.confrelid WHERE fk.contype='f' AND owned.relname='todos' AND owned.relnamespace::regnamespace::text=${schema}`.execute(db);
    assert.equal(foreignKeys.rows.length, 1); assert.equal(foreignKeys.rows[0].target_schema, schema);
    assert.equal(Number((await db.selectFrom('todos').select(sql`count(*)`.as('count')).where('deleted_at', 'is not', null).executeTakeFirst()).count), 1);
  } finally {
    if (app) await app.close();
    await base.schema.dropSchema(schema).cascade().execute();
    await base.destroy(); await rm(root, { recursive: true, force: true });
  }
});
